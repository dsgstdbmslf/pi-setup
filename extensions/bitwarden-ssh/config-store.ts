// Files of the SSH config sync: the source config (original form), the generated config, public key
// files and the Include line in ~/.ssh/config. All paths come from Paths, so tests run in temp dirs.

import { createHash, randomBytes } from "node:crypto";
import { existsSync, lstatSync, readdirSync, readFileSync, realpathSync, renameSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, dirname, isAbsolute, join } from "node:path";
import { ensureDir, type Paths } from "./paths.ts";
import { type GenerateResult, generateConfig, hostNames, parseConfig } from "./sshconfig.ts";
import type { CachedKey, State } from "./state.ts";
import { writeFileAtomic } from "./state.ts";

export function sha256(text: string): string {
	return createHash("sha256").update(text).digest("hex");
}

export function expandHome(p: string, home: string): string {
	if (p === "~") return home;
	if (p.startsWith("~/")) return join(home, p.slice(2));
	return p;
}

export function readSource(paths: Paths): string | undefined {
	try {
		return readFileSync(paths.sourceFile, "utf8");
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code === "ENOENT") return undefined;
		throw err;
	}
}

export function writeSource(paths: Paths, text: string): void {
	ensureDir(paths.dataDir);
	writeFileAtomic(paths.sourceFile, text, 0o600);
}

function safeName(name: string): string {
	return name.trim().replace(/[^A-Za-z0-9._-]+/g, "_").replace(/^\.+/, "").slice(0, 80) || "key";
}

/**
 * File name of a key's .pub file: `<sanitized name>-<first 8 chars of the item id>.pub`, all lowercase, so
 * two items never share a path, also on case-insensitive filesystems (macOS: `Foo` and `foo`). Depends
 * only on the key itself (stable across regenerations); if two ids share their first 8 chars and the names
 * fold to the same text, the full id is used.
 */
export function pubFileName(key: CachedKey, keys: CachedKey[] = []): string {
	const base = safeName(key.name).replace(/\.pub$/i, "");
	const short = (k: CachedKey) => `${safeName(k.name).replace(/\.pub$/i, "")}-${safeName(k.id.slice(0, 8))}`.toLowerCase();
	const clash = keys.some((k) => k.id !== key.id && short(k) === short(key));
	return `${clash ? `${base}-${safeName(key.id)}` : short(key)}`.toLowerCase() + ".pub";
}

export function pubPath(paths: Paths, key: CachedKey, keys: CachedKey[]): string {
	return join(paths.keysDir, pubFileName(key, keys));
}

/**
 * The cached key whose generated .pub file is `path` (reverse of pubPath). The mapping of the last
 * successfully published generation (`state.published`) wins, so a key renamed in the vault (cache
 * refreshed, publication refused) still maps the path the live config names. Then the name computed from
 * the current cache, then (state without `published`, older naming schemes) the public key in that file.
 */
export function keyForPubPath(paths: Paths, state: State, path: string): CachedKey | undefined {
	const own = dirname(path) === paths.keysDir;
	const id = own ? state.published?.[basename(path)] : undefined;
	const byId = id ? state.keys.find((k) => k.id === id) : undefined;
	if (byId) return byId;
	const byName = state.keys.find((k) => pubPath(paths, k, state.keys) === path);
	if (byName || !own || state.published) return byName;
	let text: string | undefined;
	try {
		text = readIfExists(path)?.trim();
	} catch {}
	return text ? state.keys.find((k) => k.publicKey.trim() === text) : undefined;
}

export const HEADER = (sourceFile: string) =>
	`Generated by pi bitwarden-ssh from ${sourceFile}.\nEdit via /ssh config edit or the ssh_config tool, not by hand: this file is rewritten.`;

export interface RegenerateResult extends GenerateResult {
	generatedFile: string;
}

export interface BuiltConfig extends GenerateResult {
	/** Public key files of mapped keys: path -> content. */
	pubFiles: Map<string, string>;
	/** .pub file name -> item id, to store as `state.published` together with this generation. */
	published: Record<string, string>;
}

/**
 * The exact generated config for `source` and `state`, without writing anything. Mapped identities without
 * a cached public key count as unmatched. Throws ConfigSyntaxError for lexical/arity errors in the source.
 */
export function buildGenerated(paths: Paths, state: State, source: string, opts: { controlPersist: string | false }): BuiltConfig {
	const pubFiles = new Map<string, string>();
	const published: Record<string, string> = {};
	const result = generateConfig(source, {
		mapIdentity: (p) => {
			const m = state.identityMap[p];
			if (!m) return undefined;
			const key = state.keys.find((k) => k.id === m.itemId);
			if (!key?.publicKey) return undefined;
			const file = pubPath(paths, key, state.keys);
			pubFiles.set(file, `${key.publicKey.trim()}\n`);
			published[basename(file)] = key.id;
			return file;
		},
		pathExists: (p) => existsSync(expandHome(p, paths.home)),
		controlPersist: opts.controlPersist,
		cmDir: paths.cmDir,
		header: HEADER(paths.sourceFile),
	});
	return { ...result, pubFiles, published };
}

/** A file committed after the generated config is live (source config, state.json), in this order. */
export interface AfterFile {
	file: string;
	text: string;
}

/** Steps of publishGenerated, for failure injection in tests. */
export type PublishStep = "stage" | "pub" | "generated" | "include" | "after";

export interface PublishOptions {
	/** Also make ~/.ssh/config include the generated file (after the generated file is in place). */
	include?: boolean;
	/** Written only once the new generation is live (state last: sync metadata only after success). */
	after?: AfterFile[];
	/** Tests only: called before each step; a throw simulates a failure there. */
	fault?: (step: PublishStep) => void;
}

export interface PublishResult extends RegenerateResult {
	include?: "created" | "added" | "present";
}

function readIfExists(file: string): string | undefined {
	try {
		return readFileSync(file, "utf8");
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code === "ENOENT") return undefined;
		throw err;
	}
}

interface Staged {
	file: string;
	tmp: string;
	/** Content before this publication (undefined: did not exist), for rollback. */
	prev: string | undefined;
}

/**
 * Publish `built` (public key files + generated config) and then the `after` files, as one generation:
 *
 * 1. Prepare: create/verify every directory (keys, cm, generated, after files) and read the current
 *    content of every target; a wrong path (e.g. `keys` is a regular file) fails here, before any write.
 * 2. Stage: write every new file as a temp file next to its target (`wx`, mode 600).
 * 3. Commit by renames, in an order where ssh never sees a generated config that names a missing .pub
 *    file: .pub files, the generated config, the Include in ~/.ssh/config, then the `after` files (source
 *    config, state.json last, so sync metadata is only recorded once the generation is live).
 * 4. Remove .pub files no longer referenced (best effort, only after success).
 *
 * Guarantee: on a failure before the generated config is renamed, staged temp files are removed and
 * every target keeps its old content; on a later failure, the files already committed (.pub files,
 * generated config, source) are restored to their previous content, so source, state and generated stay
 * consistent, and the error is thrown. An Include line already added stays (it names the generated file,
 * which ssh ignores if absent). If restoring the generated config itself fails, the new generated config
 * stays live, so the .pub files are not rolled back (old and new ones are kept) and the error says so.
 * Not crash-safe across a kill in the middle of step 3 (each file is atomic).
 */
export function publishGenerated(paths: Paths, built: BuiltConfig, opts: PublishOptions = {}): PublishResult {
	const fault = opts.fault ?? (() => {});
	const after = opts.after ?? [];
	// 1. Prepare.
	ensureDir(paths.sshDir);
	ensureDir(paths.keysDir);
	ensureDir(dirname(paths.cmDir)); // the /tmp fallback parent for long homes: ours, mode 700
	ensureDir(paths.cmDir);
	for (const a of after) ensureDir(dirname(a.file));
	const targets: [string, string][] = [...built.pubFiles, [paths.generatedFile, built.text], ...after.map((a): [string, string] => [a.file, a.text])];
	const prev = new Map<string, string | undefined>();
	for (const [file] of targets) {
		const st = lstatSync(file, { throwIfNoEntry: false });
		if (st?.isDirectory()) throw new Error(`${file} is a directory`);
		prev.set(file, readIfExists(file));
	}
	// 2. Stage, 3. commit.
	const staged: Staged[] = [];
	const committed: Staged[] = [];
	const stage = (file: string, text: string): Staged | undefined => {
		if (prev.get(file) === text && file !== paths.generatedFile) return undefined; // unchanged .pub/source/state
		const s: Staged = { file, tmp: join(dirname(file), `.${randomBytes(6).toString("hex")}.tmp`), prev: prev.get(file) };
		staged.push(s);
		writeFileSync(s.tmp, text, { mode: 0o600, flag: "wx" });
		return s;
	};
	const commit = (s: Staged | undefined) => {
		if (!s) return;
		renameSync(s.tmp, s.file);
		committed.push(s);
	};
	let include: PublishResult["include"];
	try {
		fault("stage");
		const pubs = [...built.pubFiles].map(([f, t]) => stage(f, t));
		const gen = stage(paths.generatedFile, built.text);
		const rest = after.map((a) => stage(a.file, a.text));
		fault("pub");
		for (const s of pubs) commit(s);
		fault("generated");
		commit(gen);
		if (opts.include) {
			fault("include");
			include = ensureInclude(paths.userConfig, paths.generatedFile);
		}
		for (const s of rest) {
			fault("after");
			commit(s);
		}
	} catch (err) {
		const failed: string[] = [];
		let keepPubs = false;
		for (const s of committed.reverse()) {
			// The new generated config is still live: keep every .pub file it may name (old ones are kept too).
			if (keepPubs && built.pubFiles.has(s.file)) continue;
			try {
				if (s.prev === undefined) unlinkSync(s.file);
				else writeFileAtomic(s.file, s.prev, 0o600);
			} catch {
				failed.push(s.file);
				if (s.file === paths.generatedFile) keepPubs = true;
			}
		}
		for (const s of staged) {
			try {
				unlinkSync(s.tmp);
			} catch {}
		}
		if (failed.length && err instanceof Error) {
			err.message += ` (rollback incomplete: could not restore ${failed.join(", ")}${keepPubs ? "; the new generated config is still live, its .pub files were kept" : ""})`;
		}
		throw err;
	}
	// 4. Obsolete .pub files (also names of the previous naming scheme), only now that nothing names them.
	for (const f of readdirSync(paths.keysDir)) {
		const full = join(paths.keysDir, f);
		if (f.endsWith(".pub") && !built.pubFiles.has(full)) {
			try {
				unlinkSync(full);
			} catch {}
		}
	}
	const { pubFiles: _, published: __, ...result } = built;
	return { ...result, generatedFile: paths.generatedFile, ...(opts.include ? { include } : {}) };
}

/** buildGenerated + publishGenerated (no ssh -G check). Returns undefined when there is no source config yet. */
export function regenerate(
	paths: Paths,
	state: State,
	opts: { controlPersist: string | false; sourceText?: string },
): RegenerateResult | undefined {
	const source = opts.sourceText ?? readSource(paths);
	if (source === undefined) return undefined;
	return publishGenerated(paths, buildGenerated(paths, state, source, opts));
}

/**
 * Make ~/.ssh/config include the generated file. Creates the file if missing; otherwise prepends the
 * Include line (an Include must come before any Host block to apply to all hosts). Only an unconditional
 * Include in the preamble (before the first Host/Match) counts as present; a copy inside a Host or Match
 * block is left alone and the global line is still prepended. Nothing else changes.
 */
export function ensureInclude(userConfig: string, generatedFile: string): "created" | "added" | "present" {
	const sshDir = join(userConfig, "..");
	const includeLine = `Include ${/[\s#'"\\]/.test(generatedFile) ? `"${generatedFile.replace(/(["\\])/g, "\\$1")}"` : generatedFile}`;
	let text: string;
	try {
		text = readFileSync(userConfig, "utf8");
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
		if (!existsSync(sshDir)) ensureDir(sshDir);
		writeFileSync(userConfig, `# Added by pi bitwarden-ssh\n${includeLine}\n`, { mode: 0o600, flag: "wx" });
		return "created";
	}
	const home = join(sshDir, "..");
	// OpenSSH resolves relative Include paths of the user config against ~/.ssh.
	const resolve = (v: string) => {
		const p = expandHome(v, home);
		return isAbsolute(p) ? p : join(sshDir, p);
	};
	const preamble = parseConfig(text)[0];
	const present = preamble.lines.some((l) => l.key === "include" && (l.args ?? []).map(resolve).includes(generatedFile));
	if (present) return "present";
	// Write through a symlinked ~/.ssh/config (dotfile setups) and keep the file's mode.
	const real = realpathSync(userConfig);
	writeFileAtomic(real, `# Added by pi bitwarden-ssh\n${includeLine}\n\n${text}`, statSync(real).mode & 0o777);
	return "added";
}

/** Host names as in the source config (for completions). */
export function sourceHosts(paths: Paths): string[] {
	try {
		const text = readSource(paths);
		if (!text) return [];
		return hostNames(parseConfig(text));
	} catch {
		return [];
	}
}
