// Files of the SSH config sync: the source config (original form), the generated config, public key
// files and the Include line in ~/.ssh/config. All paths come from Paths, so tests run in temp dirs.

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, realpathSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ensureDir, type Paths } from "./paths.ts";
import { type GenerateResult, generateConfig, hostNames, parseConfig, unquote } from "./sshconfig.ts";
import type { CachedKey, State } from "./state.ts";
import { writeFileAtomic } from "./state.ts";

export function sha256(text: string): string {
	return createHash("sha256").update(text).digest("hex");
}

export function expandHome(p: string, home: string): string {
	if (p === "~") return home;
	if (p.startsWith("~/")) return join(home, p.slice(2));
	return p;
}

export function readSource(paths: Paths): string | undefined {
	try {
		return readFileSync(paths.sourceFile, "utf8");
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code === "ENOENT") return undefined;
		throw err;
	}
}

export function writeSource(paths: Paths, text: string): void {
	ensureDir(paths.dataDir);
	writeFileAtomic(paths.sourceFile, text, 0o600);
}

function safeName(name: string): string {
	return name.trim().replace(/[^A-Za-z0-9._-]+/g, "_").replace(/^\.+/, "").slice(0, 80) || "key";
}

/** File name of a key's .pub file; keys whose safe names collide get an id suffix. */
export function pubFileName(key: CachedKey, keys: CachedKey[]): string {
	const base = safeName(key.name).replace(/\.pub$/i, "");
	const clash = keys.some((k) => k.id !== key.id && safeName(k.name).replace(/\.pub$/i, "") === base);
	return clash ? `${base}-${key.id.slice(0, 8)}.pub` : `${base}.pub`;
}

export function pubPath(paths: Paths, key: CachedKey, keys: CachedKey[]): string {
	return join(paths.keysDir, pubFileName(key, keys));
}

/** The cached key whose generated .pub file is `path` (reverse of pubPath). */
export function keyForPubPath(paths: Paths, state: State, path: string): CachedKey | undefined {
	return state.keys.find((k) => pubPath(paths, k, state.keys) === path);
}

export const HEADER = (sourceFile: string) =>
	`Generated by pi bitwarden-ssh from ${sourceFile}.\nEdit via /ssh config edit or the ssh_config tool, not by hand: this file is rewritten.`;

export interface RegenerateResult extends GenerateResult {
	generatedFile: string;
}

/**
 * Write public key files of mapped keys and the generated config. Mapped identities without a cached public
 * key count as unmatched. Returns undefined when there is no source config yet.
 */
export function regenerate(
	paths: Paths,
	state: State,
	opts: { controlPersist: string | false; sourceText?: string },
): RegenerateResult | undefined {
	const source = opts.sourceText ?? readSource(paths);
	if (source === undefined) return undefined;
	ensureDir(paths.sshDir);
	ensureDir(paths.keysDir);
	ensureDir(paths.cmDir);
	const written = new Set<string>();
	const result = generateConfig(source, {
		mapIdentity: (p) => {
			const m = state.identityMap[p];
			if (!m) return undefined;
			const key = state.keys.find((k) => k.id === m.itemId);
			if (!key?.publicKey) return undefined;
			const file = pubPath(paths, key, state.keys);
			if (!written.has(file)) {
				writeFileAtomic(file, `${key.publicKey.trim()}\n`, 0o600);
				written.add(file);
			}
			return file;
		},
		pathExists: (p) => existsSync(expandHome(p, paths.home)),
		controlPersist: opts.controlPersist,
		cmDir: paths.cmDir,
		header: HEADER(paths.sourceFile),
	});
	// Drop .pub files of keys no longer mapped.
	for (const f of readdirSync(paths.keysDir)) {
		const full = join(paths.keysDir, f);
		if (f.endsWith(".pub") && !written.has(full)) {
			try {
				unlinkSync(full);
			} catch {}
		}
	}
	writeFileAtomic(paths.generatedFile, result.text, 0o600);
	return { ...result, generatedFile: paths.generatedFile };
}

/**
 * Make ~/.ssh/config include the generated file. Creates the file if missing; otherwise prepends the
 * Include line (an Include must come before any Host block to apply to all hosts). Nothing else changes.
 */
export function ensureInclude(userConfig: string, generatedFile: string): "created" | "added" | "present" {
	const sshDir = join(userConfig, "..");
	const includeLine = `Include ${/\s/.test(generatedFile) ? `"${generatedFile}"` : generatedFile}`;
	let text: string;
	try {
		text = readFileSync(userConfig, "utf8");
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code !== "ENOENT") throw err;
		if (!existsSync(sshDir)) ensureDir(sshDir);
		writeFileSync(userConfig, `# Added by pi bitwarden-ssh\n${includeLine}\n`, { mode: 0o600, flag: "wx" });
		return "created";
	}
	const home = join(sshDir, "..");
	const present = parseConfig(text).some((b) =>
		b.lines.some(
			(l) =>
				l.key === "include" &&
				(l.value ?? "")
					.split(/\s+/)
					.map((v) => expandHome(unquote(v), home))
					.includes(generatedFile),
		),
	);
	if (present) return "present";
	// Write through a symlinked ~/.ssh/config (dotfile setups) and keep the file's mode.
	const real = realpathSync(userConfig);
	writeFileAtomic(real, `# Added by pi bitwarden-ssh\n${includeLine}\n\n${text}`, statSync(real).mode & 0o777);
	return "added";
}

/** Host names as in the source config (for completions). */
export function sourceHosts(paths: Paths): string[] {
	try {
		const text = readSource(paths);
		if (!text) return [];
		return hostNames(parseConfig(text));
	} catch {
		return [];
	}
}
